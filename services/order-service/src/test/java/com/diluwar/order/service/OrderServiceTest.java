    @Test
    void shouldBuildOrderWithCorrectCustomerAndItems() {

        CreateOrderRequest request = new CreateOrderRequest(
                3001L,
                List.of(
                        new OrderItemRequest(701L, 2, new BigDecimal("100.00")),
                        new OrderItemRequest(702L, 1, new BigDecimal("75.50"))
                )
        );

        ArgumentCaptor<Order> orderCaptor =
                ArgumentCaptor.forClass(Order.class);

        when(orderRepository.save(any(Order.class)))
                .thenAnswer(invocation -> {
                    Order order = invocation.getArgument(0);
                    order.setId(20L);
                    return order;
                });

        orderService.createOrder(request);

        verify(orderRepository).save(orderCaptor.capture());

        Order savedOrder = orderCaptor.getValue();

        assertEquals(3001L, savedOrder.getCustomerId());
        assertEquals(OrderStatus.CREATED, savedOrder.getStatus());
        assertEquals(
        new BigDecimal("275.50"),
        savedOrder.getTotalAmount()
);

        assertNotNull(savedOrder.getCreatedAt());
        assertNotNull(savedOrder.getUpdatedAt());

        assertEquals(2, savedOrder.getItems().size());

        assertEquals(701L, savedOrder.getItems().get(0).getProductId());
        assertEquals(2, savedOrder.getItems().get(0).getQuantity());
        assertEquals(
        new BigDecimal("100.00"),
        savedOrder.getItems().get(0).getUnitPrice()
);

        assertEquals(702L, savedOrder.getItems().get(1).getProductId());
        assertEquals(1, savedOrder.getItems().get(1).getQuantity());
        assertEquals(
        new BigDecimal("75.50"),
        savedOrder.getItems().get(1).getUnitPrice()
);
    }

