    @BeforeEach
    void setupInventory() {

    RestClient inventoryClient = RestClient.builder()
            .baseUrl("http://localhost:8083")
            .build();

    createInventory(inventoryClient, 501L, 100);
    createInventory(inventoryClient, 502L, 100);
    createInventory(inventoryClient, 503L, 100);
    createInventory(inventoryClient, 601L, 100);
    createInventory(inventoryClient, 602L, 100);
    createInventory(inventoryClient, 701L, 100);
}

private void createInventory(
        RestClient client,
        Long productId,
        int quantity) {

    try {
        client.post()
                .uri("/api/v1/inventory")
                .contentType(MediaType.APPLICATION_JSON)
                .body("""
                        {
                            "productId": %d,
                            "quantity": %d
                        }
                        """.formatted(productId, quantity))
                .retrieve()
                .toBodilessEntity();
    } catch (Exception ignored) {
        // Inventory may already exist from another test run.
    }
}

    @Test
    void shouldCreateOrderWithCalculatedTotal() {

        CreateOrderRequest request = new CreateOrderRequest(
                1001L,
                List.of(
                        new OrderItemRequest(101L, 2, new BigDecimal("50.00")),
                        new OrderItemRequest(102L, 3, new BigDecimal("25.00"))
                )
        );

        when(orderRepository.save(any(Order.class)))
                .thenAnswer(invocation -> {
                    Order order = invocation.getArgument(0);
                    order.setId(1L);

                    order.getItems().forEach(item -> {
                        if (item.getId() == null) {
                            // IDs are generated by the database in production.
                            // No need to assign them for this unit test.
                        }
                    });

                    return order;
                });

        OrderResponse response = orderService.createOrder(request);

        assertNotNull(response);
        assertEquals(1L, response.id());
        assertEquals(1001L, response.customerId());
        assertEquals(OrderStatus.CREATED, response.status());

        // 2 * 50 + 3 * 25 = 175
        assertEquals(
        new BigDecimal("175.00"),
        response.totalAmount()
);

        assertEquals(2, response.items().size());

        verify(orderRepository, times(1)).save(any(Order.class));
    }

